-- HOME-MADE-CRAFT Supabase setup
-- BEFORE RUNNING: replace every occurrence of YOUR-CLIENT-USER-UUID with the seller's real Auth User UID.
-- Create the client account in Supabase Authentication > Users first.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 100),
  price numeric(10,2) not null check (price > 0),
  description text not null default '',
  category text not null default 'Gifts',
  image_url text not null,
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;

-- Public visitors can read the shop's products.
create policy "Public can view products"
on public.products for select to anon, authenticated
using (true);

-- Only the designated seller account can change product rows.
create policy "Designated seller can insert products"
on public.products for insert to authenticated
with check ((select auth.uid()) = 'YOUR-CLIENT-USER-UUID'::uuid);

create policy "Designated seller can update products"
on public.products for update to authenticated
using ((select auth.uid()) = 'YOUR-CLIENT-USER-UUID'::uuid)
with check ((select auth.uid()) = 'YOUR-CLIENT-USER-UUID'::uuid);

create policy "Designated seller can delete products"
on public.products for delete to authenticated
using ((select auth.uid()) = 'YOUR-CLIENT-USER-UUID'::uuid);

-- Create a public image bucket. Public means anyone can VIEW product photos;
-- upload/delete still require the authenticated seller policies below.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('product-images', 'product-images', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 5242880,
  allowed_mime_types = array['image/jpeg','image/png','image/webp'];

create policy "Public can view product images"
on storage.objects for select to anon, authenticated
using (bucket_id = 'product-images');

create policy "Designated seller can upload product images"
on storage.objects for insert to authenticated
with check (
  bucket_id = 'product-images'
  and (select auth.uid()) = 'YOUR-CLIENT-USER-UUID'::uuid
);

create policy "Designated seller can delete product images"
on storage.objects for delete to authenticated
using (
  bucket_id = 'product-images'
  and (select auth.uid()) = 'YOUR-CLIENT-USER-UUID'::uuid
);
